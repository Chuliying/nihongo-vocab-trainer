def to_kana(text: str) -> str:
    return "".join(part["hira"] for part in KAKASI.convert(text))


def has_placeholder(text: str) -> bool:
    return any(marker in text for marker in PLACEHOLDER_MARKERS)


def fallback_curated(entry: dict) -> tuple[str, str, str, str]:
    word = entry["word"]
    pos_tokens = set(entry["part_of_speech"].split("・"))

    if word in FRAGMENT_OR_INFLECTION_WORDS:
        return (
            f"活用・口語形式:{word}(要確認)",
            f"会話では「{word}」という形を見かけることがあります。",
            f"在會話中有時會看到「{word}」這種形式。",
            "needs_review",
        )
    if word in FUNCTION_MEANINGS:
        meaning, jp, zh = FUNCTION_MEANINGS[word]
        return meaning, jp, zh, "curated"
    if "助詞" in pos_tokens or "助動詞" in pos_tokens:
        return (
            f"文法形式:{word}",
            f"短い文で「{word}」の働きを確認しました。",
            f"用短句確認了「{word}」的文法作用。",
            "needs_review",
        )
    if "副詞" in pos_tokens:
        return (
            f"副詞:{word}",
            f"会話で「{word}」を使うことがあります。",
            f"會話中有時會使用「{word}」。",
            "needs_review",
        )
    if "動詞" in pos_tokens:
        return (
            word,
            f"必要な時に{word}ことがあります。",
            f"有時候會做「{word}」這個動作。",
            "needs_review",
        )
    if re.search(r"[\u30a0-\u30ff]", word):
        return (
            word,
            f"友達と{word}について話しました。",
            f"和朋友聊到了「{word}」。",
            "needs_review",
        )
    return (
        word,
        f"日常会話で「{word}」という言葉を聞くことがあります。",
        f"日常會話中有時會聽到「{word}」這個說法。",
        "needs_review",
    )


def main() -> None:
    vocab = json.loads(VOCAB_PATH.read_text(encoding="utf-8"))

    # First entry per word within Tranche 1
    t1_by_word: dict[str, dict] = {}
    for entry in vocab:
        if entry["tranche_id"] == 1 and entry["word"] not in t1_by_word:
            t1_by_word[entry["word"]] = entry

    # Sanity: every example must contain its headword's dictionary form,
    # matching scripts/validate_vocab.py's rule.
    bad = [w for w, (_, jp, _) in CURATED.items() if not example_has_headword(w, jp)]
    if bad:
        raise SystemExit(f"example does not contain headword: {', '.join(bad)}")

    applied = 0
    not_found = []
    for word, (meaning, jp, zh) in CURATED.items():
        entry = t1_by_word.get(word)
        if entry is None:
            not_found.append(word)
            continue
        if entry.get("quality_score") == "verb_curated":
            continue
        # This table is authoritative for the words it lists; always apply.
        entry["meaning"] = meaning
        entry["example"] = {
            "japanese": jp,
            "reading": to_kana(jp),
            "chinese": zh,
        }
        entry["quality_score"] = "curated"
        entry["source"]["example"] = "curated"
        q = entry.setdefault("_quality", {})
        q["quality_score"] = "curated"
        q["meaning_source"] = "hand curated (T1)"
        q["example_source"] = "hand curated (T1)"
        applied += 1

    auto_applied = 0
    for entry in vocab:
        if entry["tranche_id"] != 1 or not has_placeholder(entry["meaning"]):
            continue
        meaning, jp, zh, quality_score = fallback_curated(entry)
        entry["meaning"] = meaning
        entry["example"] = {
            "japanese": jp,
            "reading": to_kana(jp),
            "chinese": zh,
        }
        entry["quality_score"] = quality_score
        entry["source"]["example"] = quality_score
        q = entry.setdefault("_quality", {})
        q["quality_score"] = quality_score
        q["meaning_source"] = "T1 placeholder cleanup"
        q["example_source"] = "T1 placeholder cleanup"
        auto_applied += 1

    VOCAB_PATH.write_text(
        json.dumps(vocab, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"Curated {applied} Tranche-1 entries.")
    print(f"Cleaned {auto_applied} remaining Tranche-1 placeholder entries.")
    if not_found:
        print(f"Not found in Tranche 1 (skipped): {', '.join(not_found)}")


if __name__ == "__main__":
    main()
