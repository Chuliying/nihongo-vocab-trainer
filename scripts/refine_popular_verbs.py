def main():
    vocab = json.loads(VOCAB_PATH.read_text(encoding="utf-8"))
    popular = json.loads(POPULAR_PATH.read_text(encoding="utf-8"))
    by_id = {entry["id"]: entry for entry in vocab}
    popular_ids = {item["id"] for item in popular}

    for entry in vocab:
        if entry["id"] in popular_ids or entry.get("quality_score") != "verb_curated":
            continue
        if has_placeholder(entry.get("meaning", "")) or has_low_value_example(entry.get("example", {}).get("japanese", "")):
            entry["quality_score"] = "needs_review"
            entry.setdefault("_quality", {})["quality_score"] = "needs_review"
            entry.setdefault("_quality", {})["meaning_source"] = "demoted stale verb curated"
            entry.setdefault("_quality", {})["example_source"] = "demoted stale verb curated"

    for item in popular:
        entry = by_id[item["id"]]
        meaning, jp, zh = CURATED.get(entry["word"], semantic_curated(entry))
        entry["meaning"] = meaning
        entry["example"] = {
            "japanese": jp,
            "reading": to_kana(jp),
            "chinese": zh,
        }
        entry["quality_score"] = "verb_curated"
        entry.setdefault("_quality", {})["quality_score"] = "verb_curated"
        entry.setdefault("_quality", {})["meaning_source"] = "verb curated"
        entry.setdefault("_quality", {})["example_source"] = "verb curated"
        entry["source"]["example"] = "verb curated"
        item["meaning"] = meaning

        if has_placeholder(meaning):
            raise SystemExit(f"{entry['word']} still has placeholder meaning")

    VOCAB_PATH.write_text(json.dumps(vocab, ensure_ascii=False, indent=2), encoding="utf-8")
    POPULAR_PATH.write_text(json.dumps(popular, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Refined {len(popular)} popular verbs.")


if __name__ == "__main__":
    main()
