def to_kana(text: str) -> str:
    return "".join(part["hira"] for part in KAKASI.convert(text))


def has_placeholder(text: str) -> bool:
    return any(marker in text for marker in PLACEHOLDER_MARKERS)


def has_low_value_example(text: str) -> bool:
    return any(pattern in text for pattern in LOW_VALUE_EXAMPLE_PATTERNS)


def first_gloss(entry: dict) -> str:
    glosses = entry.get("_quality", {}).get("gloss_en", [])
    return (glosses[0] if glosses else "").lower()


