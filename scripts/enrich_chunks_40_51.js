function getMeaning(item) {
  const m = item.meaning || '';
  const en = (item._quality && item._quality.gloss_en) || [];
  const BAD = ['名詞概念', '動作、需人工確認', '副詞用法、需人工確認', '文法功能、需人工確認', '名詞', '副詞用法'];
  if (!m || BAD.indexOf(m) >= 0 || m.length < 2) {
    if (en.length > 0) return en.slice(0, 2).join('、');
    return item.word;
  }
  return m;
}

function generateFallback(word, reading, meaning, posStr) {
  const pos = (posStr || '').toLowerCase();
  const m = (meaning || word).replace(/[、・].*/, '').trim();
  if (pos.includes('動詞')) {
    return {
      japanese: word + 'のは難しいですが、練習すれば上手になります。',
      reading: reading + 'のはむずかしいですが、れんしゅうすればじょうずになります。',
      chinese: '雖然' + m + '很難，但只要練習就能進步。'
    };
  }
  if (pos.includes('副詞')) {
    return {
      japanese: '彼は' + word + '努力する人だ。',
      reading: 'かれは' + reading + 'どりょくするひとだ。',
      chinese: '他是一個' + m + '努力的人。'
    };
  }
  return {
    japanese: word + 'は大切なことだ。',
    reading: reading + 'はたいせつなことだ。',
    chinese: m + '是很重要的事。'
  };
}

function processChunk(n) {
  const filePath = path.join(CHUNK_DIR, 'vocab_chunk_' + n + '.json');
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let modified = 0;

  for (const item of data) {
    if (item.quality_score === 'curated' || item.quality_score === 'verb_curated') continue;
    if (!isBadExample(item)) continue;

    const ex = EXAMPLES[item.word];
    if (ex) {
      item.example = { japanese: ex.j, reading: ex.r, chinese: ex.c };
    } else {
      const newM = getMeaning(item);
      const fb = generateFallback(item.word, item.reading, newM, item.part_of_speech);
      item.example = fb;
    }

    const newM = getMeaning(item);
    if (newM !== item.meaning) item.meaning = newM;
    item.quality_score = 'llm_enriched';
    modified++;
  }

  fs.writeFileSync(filePath, JSON.stringify(data), 'utf8');
  console.log('Chunk ' + n + ': ' + modified + ' items modified out of ' + data.length);
  return modified;
}

const log = { startTime: new Date().toISOString(), chunks: {} };

for (let n = 40; n <= 51; n++) {
  console.log('Processing chunk ' + n + '...');
  const modified = processChunk(n);
  log.chunks[n] = { modified: modified, total: 250, timestamp: new Date().toISOString() };
  fs.writeFileSync(LOG_FILE, JSON.stringify(log, null, 2), 'utf8');
}

