// -----------------------------------------------------------------------
// Detect placeholder/bad examples
// -----------------------------------------------------------------------
function isPlaceholder(ex, word) {
  if (!ex || !ex.japanese) return true;
  const jp = ex.japanese;
  // Generic meta-sentences that talk about the word instead of using it
  const metaPatterns = [
    /「[^」]+」の使い方を(確認|説明)/,
    /「[^」]+」のことを話しました/,
    /「[^」]+」という言葉を(見|聞)/,
    /「[^」]+」という言葉が出ました/,
    /「[^」]+」を使った文を書きました/,
    /「[^」]+」を(調べ|調査)/,
    /「[^」]+」は文の中でよく使います/,
    /「[^」]+」を入れると文の/,
    /「[^」]+」という字を(見|調べ)/,
    /「[^」]+」の働きを確認/,
    /日常生活で[ァ-ヶー]+(を使うことがあります|を使います)/,
    /日常会話で「[^」]+」という言葉を聞くことがあります/,
    /「[^」]+」という表現を聞きました/,
    /「[^」]+」と言いました/,
    /「[^」]+」を正しく使いたいです/,
    /「[^」]+」の自然な言い方を教えました/,
    /「[^」]+」の反対の意味/,
    /「[^」]+」を使った例を出しました/,
    /「[^」]+」の使う場面を説明/,
  ];
  for (const pat of metaPatterns) {
    if (pat.test(jp)) return true;
  }
  // Check if the chinese translation is also meta
  if (ex.chinese && /「[^」]+」(這個說法|的用法|的作用)/.test(ex.chinese)) return true;
  return false;
}

// -----------------------------------------------------------------------
// Example generation based on word, reading, meaning, POS
// -----------------------------------------------------------------------
function generateExample(item) {
  const { word, reading, meaning, part_of_speech, jlpt_level } = item;
  
  // Look up in manual curated examples first
  if (MANUAL_EXAMPLES[item.id]) {
    return MANUAL_EXAMPLES[item.id];
  }
  
  // Auto-generate based on word type and meaning
  return autoGenerate(word, reading, meaning, part_of_speech);
}

// -----------------------------------------------------------------------
// Auto-generation logic based on categories
// -----------------------------------------------------------------------
function autoGenerate(word, reading, meaning, pos) {
  const w = word;
  const r = reading;
  const m = meaning;
  const p = pos || '';
  
  // === NOUNS (名詞) ===
  if (p.includes('名詞') && !p.includes('動詞') && !p.includes('形容')) {
    return genNoun(w, r, m);
  }
  
  // === ADJECTIVES ===
  if (p.includes('形容動詞') || p.includes('形容詞')) {
    return genAdj(w, r, m, p);
  }
  
  // === ADVERBS ===
  if (p.includes('副詞')) {
    return genAdv(w, r, m);
  }
  
  // === CONJUNCTION ===
  if (p.includes('接続詞')) {
    return genConj(w, r, m);
  }
  
  // === PARTICLES ===
  if (p.includes('助詞')) {
    return genParticle(w, r, m);
  }
  
  // === EXPRESSIONS ===
  if (p.includes('感動詞') || p.includes('表現')) {
    return genExpr(w, r, m);
  }
  
  // Default
  return genDefault(w, r, m);
}

function genNoun(w, r, m) {
  // Choose based on meaning
  const templates = [
    // General usage templates for nouns
    () => ({ japanese: `${w}のことが気になっています。`, reading: `${r}のことがきになっています。`, chinese: `我很在意${m}的事情。` }),
    () => ({ japanese: `今日、友達と${w}について話しました。`, reading: `きょう、ともだちと${r}についてはなしました。`, chinese: `今天和朋友聊到了關於${m}的話題。` }),
    () => ({ japanese: `${w}は生活の中でよく使われます。`, reading: `${r}はせいかつのなかでよくつかわれます。`, chinese: `${m}在生活中經常被使用。` }),
  ];
  return templates[0]();
}

function genAdj(w, r, m, p) {
  if (p.includes('な') || p.includes('形容動詞')) {
    return {
      japanese: `この部屋は${w}な雰囲気がありますね。`,
      reading: `このへやは${r}なふんいきがありますね。`,
      chinese: `這個房間有著${m}的氛圍呢。`
    };
  }
  return {
    japanese: `彼女はとても${w}人です。`,
    reading: `かのじょはとても${r}ひとです。`,
    chinese: `她是個非常${m}的人。`
  };
}

