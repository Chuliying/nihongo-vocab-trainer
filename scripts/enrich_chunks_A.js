function processChunk(chunkNum) {
  const filePath = `/Users/Chuliying/nihongo-vocab-trainer/public/data/chunks/vocab_chunk_${chunkNum}.json`;
  let data;
  try {
    data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (e) {
    console.error(`Error reading chunk ${chunkNum}:`, e.message);
    return 0;
  }

  let modified = 0;
  const updated = data.map(item => {
    if (item.quality_score === 'curated' || item.quality_score === 'verb_curated') {
      return item;
    }
    
    const newEx = MANUAL_EXAMPLES[item.id];
    if (newEx) {
      modified++;
      return { ...item, example: newEx, quality_score: 'llm_enriched' };
    }
    
    // Check if current example is a placeholder
    if (isPlaceholder(item.example, item.word)) {
      // Generate a simple but natural example using autoGenerate
      const autoEx = autoGenerate(item.word, item.reading, item.meaning, item.part_of_speech);
      if (autoEx) {
        modified++;
        return { ...item, example: autoEx, quality_score: 'llm_enriched' };
      }
    }
    
    // Example is already OK or can't be improved
    return item;
  });

  fs.writeFileSync(filePath, JSON.stringify(updated), 'utf8');
  console.log(`Chunk ${chunkNum}: ${modified} modified out of ${data.length} total (${data.length - modified - data.filter(i => i.quality_score === 'curated' || i.quality_score === 'verb_curated').length} unchanged non-curated)`);
  return modified;
}

