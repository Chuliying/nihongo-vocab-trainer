function isPlaceholder(ex, word) {
  if (!ex || !ex.japanese) return true;
  const jp = ex.japanese;
  const metaPatterns = [
    /「[^」]+」の使い方を(確認|説明)/,
    /「[^」]+」のことを話しました/,
    /「[^」]+」という言葉を(見|聞)/,
    /「[^」]+」という言葉が出ました/,
    /「[^」]+」を使った文を書きました/,
    /「[^」]+」を(調べ|調査)/,
    /「[^」]+」は文の中でよく使います/,
    /「[^」]+」を入れると文の/,
    /「[^」]+」という字を(見|調べ)/,
    /「[^」]+」の働きを確認/,
    /日常生活で[ァ-ヶー]+(を使うことがあります|を使います)/,
    /日常会話で「[^」]+」という言葉を聞くことがあります/,
    /「[^」]+」という表現を聞きました/,
    /「[^」]+」という表現を使いました/,
    /「[^」]+」と言いました.*朋友說了/,
    /「[^」]+」を正しく使いたいです/,
    /「[^」]+」の自然な言い方を教えました/,
    /「[^」]+」の反対の意味/,
    /「[^」]+」を使った例を出しました/,
    /「[^」]+」の使う場面を説明/,
    /日記に「[^」]+」を使った文/,
    /辞書で「[^」]+」を調べました/,
    /作文に「[^」]+」を入れると/,
    /作文で「[^」]+」を正しく/,
    /ニュースで「[^」]+」という言葉を聞きました/,
    /授業で「[^」]+」について話しました/,
    /先生は「[^」]+」の使い方を説明しました/,
    /本の中で「[^」]+」という(言葉|字)を(見|調べ)/,
    /友達と「[^」]+」のことを話しました/,
    /会話の中で「[^」]+」という言葉が出ました/,
    /会話で「[^」]+」という表現を聞きました/,
    /「[^」]+」は文の/,
    /短い文で「[^」]+」/,
  ];
  for (const pat of metaPatterns) {
    if (pat.test(jp)) return true;
  }
  if (ex.chinese && /「[^」]+」(這個說法|的用法|的作用|這個表現)/.test(ex.chinese)) return true;
  return false;
}

function autoGenerate(word, reading, meaning, pos) {
  const p = pos || '';
  const m = meaning || '';
  const w = word;
  const r = reading;
  
  // Katakana loanwords - need specific templates
  if (/^[ァ-ヶー]+$/.test(w)) {
    return genKatakana(w, r, m);
  }
  
  // Numbers / basic items
  if (/^[0-9一二三四五六七八九十百千万億]+$/.test(w)) {
    return { japanese: `${w}人の学生がいます。`, reading: `${r}にんのがくせいがいます。`, chinese: `有${m}個學生。` };
  }
  
  // Particles
  if (p.includes('助詞') && !p.includes('名詞')) {
    return genParticleFull(w, r, m);
  }
  
  // Conjunctions
  if (p.includes('接続詞')) {
    return { japanese: `雨が降り始めました。${w}、傘を持って出かけました。`, reading: `あめがふりはじめました。${r}、かさをもってでかけました。`, chinese: `開始下雨了。${m}，帶著傘出門了。` };
  }
  
  // Interjections / expressions
  if (p.includes('感動詞')) {
    return { japanese: `${w}、それは知りませんでした。`, reading: `${r}、それはしりませんでした。`, chinese: `${m}，這個我不知道。` };
  }
  
  // Adverbs
  if (p.includes('副詞')) {
    return genAdvFull(w, r, m);
  }
  
  // Na-adjectives
  if (p.includes('形容動詞')) {
    return { japanese: `この映画はとても${w}な内容です。`, reading: `このえいがはとても${r}ないようです。`, chinese: `這部電影的內容非常${m}。` };
  }
  
  // I-adjectives
  if (p.includes('形容詞') && !p.includes('形容動詞')) {
    return { japanese: `今日の天気はとても${w}です。`, reading: `きょうのてんきはとても${r}です。`, chinese: `今天的天氣非常${m}。` };
  }
  
  // Verbs - should be handled by verb_curated, but just in case
  if (p.includes('動詞')) {
    return { japanese: `毎日${w}ことが大切です。`, reading: `まいにち${r}ことがたいせつです。`, chinese: `每天${m}是很重要的事。` };
  }
  
  // Default for nouns and others
  return genNounFull(w, r, m, p);
}

function genKatakana(w, r, m) {
  // Specific handling for common katakana words
  const templates = [
    { japanese: `${w}を使って仕事をしています。`, reading: `${r}をつかってしごとをしています。`, chinese: `使用${m}在工作。` },
    { japanese: `${w}はとても便利です。`, reading: `${r}はとてもべんりです。`, chinese: `${m}非常方便。` },
    { japanese: `新しい${w}を買いました。`, reading: `あたらしい${r}をかいました。`, chinese: `買了新的${m}。` },
  ];
  return templates[Math.floor(Math.random() * templates.length)];
}

function genParticleFull(w, r, m) {
  return { japanese: `彼は疲れていて、食事${w}できないほどでした。`, reading: `かれはつかれていて、しょくじ${r}できないほどでした。`, chinese: `他累到${m}連吃飯都做不到的程度。` };
}

